#!/usr/bin/env node
/**
 * Prepares `dist/` for a Cloudflare Pages preview.
 *
 * It touches no production and publishes nothing: it only writes the files
 * Cloudflare Pages reads and GitHub Pages ignores.
 *
 *   - `_headers`: the real CSP (the same one as `infra/cloudflare/csp.txt`),
 *     noindex, and long caching for hashed assets.
 *   - `robots.txt`: Disallow / so a crawler does not follow production's
 *     sitemap from a review URL.
 *   - removes `CNAME`, which only GitHub Pages understands and here is
 *     misleading.
 *
 * Usage: node scripts/prepare-preview.mjs   (after npm run build)
 */
import { execSync } from 'node:child_process';
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DIST = join(ROOT, 'dist');

if (!existsSync(join(DIST, 'index.html'))) {
  console.error('No dist/index.html. Run `npm run build` first.');
  process.exit(1);
}

const cspPath = join(ROOT, 'infra/cloudflare/csp.txt');
if (!existsSync(cspPath)) {
  console.error('Missing infra/cloudflare/csp.txt: the CSP is the single source.');
  process.exit(1);
}

const csp = readFileSync(cspPath, 'utf8').trim();
if (!csp.startsWith("default-src 'self'") || csp.includes('\n')) {
  console.error('infra/cloudflare/csp.txt must be a single line starting with default-src.');
  process.exit(1);
}

function git(command, fallback) {
  try {
    return execSync(command, { cwd: ROOT, encoding: 'utf8' }).trim();
  } catch {
    return fallback;
  }
}

const commit = git('git rev-parse --short HEAD', 'no-git');
const built = new Date().toISOString();

const headers = `# Generated by scripts/prepare-preview.mjs for Cloudflare Pages.
# Not versioned: it lives in dist/ and only exists in the preview.
/*
  Content-Security-Policy: ${csp}
  Permissions-Policy: accelerometer=(), camera=(), geolocation=(), gyroscope=(), magnetometer=(), microphone=(), payment=(), usb=()
  Referrer-Policy: strict-origin-when-cross-origin
  X-Content-Type-Options: nosniff
  X-Frame-Options: SAMEORIGIN
  X-Robots-Tag: noindex, nofollow
  X-Preview-Commit: ${commit}
  X-Preview-Built: ${built}

/_astro/*
  Cache-Control: public, max-age=31536000, immutable

/sw.js
  Cache-Control: no-store
`;

writeFileSync(join(DIST, '_headers'), headers, 'utf8');

writeFileSync(
  join(DIST, 'robots.txt'),
  '# Preview: do not index. Production uses public/robots.txt.\nUser-agent: *\nDisallow: /\n',
  'utf8',
);

if (existsSync(join(DIST, 'CNAME'))) {
  rmSync(join(DIST, 'CNAME'));
}

console.log('dist/ prepared for Cloudflare Pages');
console.log(`  commit: ${commit}`);
console.log('  headers: noindex, CSP from infra/cloudflare/csp.txt, /_astro/* immutable');
console.log('  robots.txt: Disallow /');
console.log('  CNAME: removed (only GitHub Pages uses it)');
